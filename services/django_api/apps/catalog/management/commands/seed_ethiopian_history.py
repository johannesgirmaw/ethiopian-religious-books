def _build_chapters_draft() -> list[dict]:
    raw: list[dict] = []
    for chapter in CHAPTER_BLUEPRINTS:
        raw.append(
            {
                "title": chapter["title"],
                "pages": [
                    {"title": title, "body": body}
                    for title, body in chapter["pages"]
                ],
            }
        )
    return normalize_chapters_draft(raw)


